"""Targeted finite cyclic quotients of two rank-three pure-cone shapes.

Not a modulus sweep: full-rank matrices are generated by three necessary
doubling-closure relations. Only their determinant-divisor cyclic images
are examined. Uses the earlier modular kernel solver, not its old searches.
Default cooperative global deadline: 30 seconds. Timeouts remain INCOMPLETE.
The deadline is checked between steps, not inside a single kernel solve.
"""

import argparse
from collections import Counter
from hashlib import sha256
from itertools import combinations_with_replacement, product
from math import gcd
import json
from pathlib import Path
from time import monotonic

from stage10_modular_audit import factors, local_projective_kernel


POINTS = {
    "I": ((0, 0, 0), (1, 0, 0), (-2, 0, 0), (0, 1, 0),
          (0, -2, 0), (0, 0, 1), (0, 0, 3), (0, 0, -5)),
    "II": ((0, 0, 0), (1, 0, 0), (-2, 0, 0), (0, 1, 0),
           (0, -2, 0), (0, 0, 1), (-2, 0, 2), (2, 0, -4)),
}


class DeadlineReached(Exception):
    pass


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def normalize(row):
    row = tuple(row)
    assert any(row)
    # Only powers of two are invertible uniformly in the odd target group.
    while all(x % 2 == 0 for x in row):
        row = tuple(x // 2 for x in row)
    if next(x for x in row if x) < 0:
        row = tuple(-x for x in row)
    return row


def functional(rows):
    if not rows:
        return (0, 0, 1)
    if len(rows) == 1:
        for basis in ((1, 0, 0), (0, 1, 0), (0, 0, 1)):
            answer = cross(rows[0], basis)
            if any(answer):
                return answer
    assert len(rows) == 2
    answer = cross(*rows)
    assert any(answer)
    return answer


def matrices(differences, counts, deadline):
    def visit(rows):
        if monotonic() > deadline:
            raise DeadlineReached
        counts["rank_" + str(len(rows)) + "_nodes"] += 1
        if len(rows) == 3:
            yield tuple(sorted(rows))
            return
        f = functional(rows)
        assert all(dot(f, row) == 0 for row in rows)
        selected = max(differences, key=lambda d: dot(f, d))
        maximum = dot(f, selected)
        assert maximum > 0
        extensions = set()
        for e in differences:
            row = tuple(2 * d - x for d, x in zip(selected, e))
            assert dot(f, row) >= maximum
            extensions.add(normalize(row))
        counts["rank_" + str(len(rows)) + "_extensions"] += len(extensions)
        for row in sorted(extensions):
            yield from visit(rows + (row,))
    yield from visit(())


def embed_adjugate(rows):
    (a, b, c), (d, e, f), (g, h, i) = rows
    columns3 = ((e*i-f*h, f*g-d*i, d*h-e*g),
                (c*h-b*i, a*i-c*g, b*g-a*h),
                (b*f-c*e, c*d-a*f, a*e-b*d))
    determinant = a*columns3[0][0] + b*columns3[0][1] + c*columns3[0][2]
    assert determinant != 0
    matrix = tuple(row + (0,) for row in rows) + ((0, 0, 0, 1),)
    columns = tuple(col + (0,) for col in columns3) + ((0, 0, 0, determinant),)
    assert all(dot(row, col) == determinant * (r == j)
               for r, row in enumerate(matrix) for j, col in enumerate(columns))
    return matrix, determinant, columns


def quotient_images(matrix, determinant, columns, counts, deadline):
    odd = abs(determinant)
    while odd % 2 == 0:
        odd //= 2
    prime_factors = factors(odd)
    local_cache = {}
    for exponents in product(*(range(e + 1) for _, e in prime_factors)):
        if monotonic() > deadline:
            raise DeadlineReached
        selected = [(p, e) for (p, _), e in zip(prime_factors, exponents) if e]
        n = 1
        for p, e in selected:
            n *= p ** e
        if not 188 <= n <= 2187:
            continue
        counts["derived_divisor_orders"] += 1
        kernels = []
        for p, e in selected:
            if (p, e) not in local_cache:
                vectors, difficult = local_projective_kernel(matrix, columns, p, e)
                local_cache[p, e] = vectors
                counts["low_rank_local_kernel_calls"] += difficult
            kernels.append(local_cache[p, e])
        for vectors in product(*kernels):
            if monotonic() > deadline:
                raise DeadlineReached
            x = [0] * 4
            for (p, e), v in zip(selected, vectors):
                q = p ** e
                other = n // q
                multiplier = other * pow(other, -1, q)
                x = [a + multiplier*b for a, b in zip(x, v)]
            x = tuple(value % n for value in x)
            assert x[3] == 0 and gcd(n, *x) == 1
            assert all(dot(row, x) % n == 0 for row in matrix)
            counts["quotient_maps_up_to_units"] += 1
            yield n, x[:3]


def check_family(name, start, deadline):
    points = POINTS[name]
    differences = sorted({tuple(x-y for x, y in zip(a, b))
                          for a in points for b in points if a != b})
    assert len(differences) == 56
    counts = Counter()
    seen = set()
    image_seen = set()
    closure_survivors = []
    valid_survivors = []
    digest = sha256()
    complete = False
    try:
        for rows in matrices(differences, counts, deadline):
            if rows in seen:
                counts["duplicate_matrices"] += 1
                continue
            seen.add(rows)
            digest.update(repr(rows).encode("ascii") + b"\n")
            counts["distinct_full_rank_matrices"] += 1
            matrix, det, columns = embed_adjugate(rows)
            odd = abs(det)
            while odd % 2 == 0:
                odd //= 2
            if odd < 188:
                counts["small_odd_determinants"] += 1
                continue
            for n, vector in quotient_images(matrix, det, columns, counts, deadline):
                a = tuple(dot(p, vector) % n for p in points)
                key = (n, a)
                if key in image_seen:
                    counts["duplicate_quotient_images"] += 1
                    continue
                image_seen.add(key)
                counts["distinct_quotient_images"] += 1
                if len(set(a)) != 8:
                    counts["repeated_point_images"] += 1
                    continue
                if len({(x+y) % n for x, y in combinations_with_replacement(a, 2)}) != 36:
                    counts["pair_sum_failure_images"] += 1
                    continue
                counts["sidon_images"] += 1
                delta = {(x-y) % n for x in a for y in a if x != y}
                if any(2*d % n not in delta for d in delta):
                    counts["doubling_closure_failure_images"] += 1
                    continue
                record = {"N": n, "A": a, "parameters": vector, "rows": rows}
                closure_survivors.append(record)
                counts["doubling_closed_images"] += 1
                target = sum(a) % n
                rival = None
                for indices in combinations_with_replacement(range(8), 8):
                    if monotonic() > deadline:
                        raise DeadlineReached
                    counts["validity_multisets_checked"] += 1
                    if indices != tuple(range(8)) and sum(a[i] for i in indices) % n == target:
                        rival = indices
                        break
                if rival is not None:
                    record["rival"] = rival
                    counts["invalid_closed_images"] += 1
                else:
                    valid_survivors.append(record)
        complete = True
    except DeadlineReached:
        pass
    return {"family": name, "completion_status": "complete" if complete else "INCOMPLETE: cap reached",
            "elapsed_since_global_start": monotonic()-start,
            "counts": dict(sorted(counts.items())),
            "matrix_prefix_sha256": digest.hexdigest(),
            "closure_survivors": closure_survivors,
            "valid_survivors": valid_survivors}


def run(cap):
    start = monotonic()
    deadline = start+cap
    records = []
    for name in POINTS:
        if monotonic() > deadline:
            records.append({"family": name, "completion_status": "NOT STARTED: global cap reached"})
        else:
            records.append(check_family(name, start, deadline))
    complete = all(r["completion_status"] == "complete" for r in records)
    return {"scope": "Two fixed rank-three pure-cone closure presentations; determinant-divisor quotients only",
            "runtime_cap_seconds": cap, "elapsed_seconds": monotonic()-start,
            "completion_status": "complete" if complete else "INCOMPLETE",
            "complete_two_family_exclusion": complete and all(not r["valid_survivors"] for r in records),
            "families": records,
            "dependencies": ["Stage12 elementary reduction to two pure-cone families",
                             "Stage5 elementary H<=2187; elementary cubic packing H>=188 here",
                             "Stage10 modular kernel routines reused, not historical searches"],
            "limitations": ["Any timeout excludes only the processed prefix, not the shape.",
                            "The checked deadline is cooperative, not a preemptive wall-clock kill.",
                            "Other four core cones and quartic fibers coning no triple are not covered.",
                            "This is a finite computation, not an elementary exclusion or novelty claim."]}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--cap", type=float, default=30)
    parser.add_argument("--output", default="stage13_pure_cone_results.json")
    args = parser.parse_args()
    result = run(args.cap)
    Path(args.output).write_text(json.dumps(result, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(result, indent=2))
